const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const compiled = G.map(g => ({ ...g, re: new RegExp('(?:^|[^a-z])(?:' + (g.m || [escRe(g.w) + 's?']).join('|') + ')(?![a-z])', 'i') }));

const BASIC = new Set(['value', 'sum / product', 'difference', 'point', 'line', 'side', 'angle', 'area', 'expression', 'equation', 'integer', 'quantity', 'indicate all', 'list', 'digit', 'odd / even', 'term', 'measure (of an angle)', 'percent', 'fraction', 'circle', 'triangle', 'center']);
function plain(html) { return String(html || '').replace(/<sup>(.*?)<\/sup>/g, '^$1').replace(/<[^>]+>/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\s+/g, ' '); }

// returns [{word, meaning}] for terms appearing in the question (text, choices, quantities)
function vocabFor(q) {
  const text = plain([q.stimulus, q.questionText, q.qa, q.qb, ...(q.type === 'QC' ? [] : (q.choices || []).map(c => c.text))].join(' '))
    .replace(/Note: Figure not drawn to scale\./, ' drawn to scale ');
  const hit = compiled.filter(g => g.re.test(text));
  const core = hit.filter(g => !BASIC.has(g.w)), basic = hit.filter(g => BASIC.has(g.w));
  return [...core, ...basic].slice(0, 12).map(g => ({ word: g.w, meaning: g.k }));
}

module.exports = { GLOSSARY: G, vocabFor };
