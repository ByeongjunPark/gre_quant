'use strict';
// Builds 20 GRE Quant mock tests: Quant_Mock_XX.html (exam data) + js/quant_explanations_XX.js (Korean explanations)
const fs = require('fs');
const path = require('path');
const { Rng } = require('./lib');
const { finalize } = require('./make');
const { diGrowth, diBudget } = require('./t_di');

const TEMPLATES = [...require('./t_arith'), ...require('./t_alg'), ...require('./t_qc'), ...require('./t_geo'), ...require('./t_data'), ...require('./t_fig')];
const ROOT = path.join(__dirname, '..');
const NUM_TESTS = 20;
const SEED = 20261106;

const FIG_IDS = new Set(['rectpd', 'lineaxes', 'circsq', 'segment', 'eqtri', 'similar', 'qc_tri3']);
TEMPLATES.forEach(t => { if (FIG_IDS.has(t.id)) t.fig = true; });
const usage = {};
TEMPLATES.forEach(t => { usage[t.id] = 0; });

function pickTemplate(r, fmt, usedInTest, areaCount, wantFig) {
  const cands = TEMPLATES.filter(t => t.formats.includes(fmt) && !usedInTest.has(t.id));
  let best = null, bestScore = Infinity;
  for (const t of cands) {
    const s = usage[t.id] * 10 + (areaCount[t.area] || 0) * 4 + r.next() * 6 - (wantFig && t.fig ? 25 : 0);
    if (s < bestScore) { bestScore = s; best = t; }
  }
  return best;
}

function genItem(t, fmt, r) {
  for (let tries = 0; tries < 30; tries++) {
    try {
      const core = t.gen(r, fmt);
      if (fmt === 'QC' && core.kind !== 'qc' && !core.noun) continue;
      return finalize(t, core, fmt, r);
    } catch (e) {
      if (tries === 29) throw new Error(`${t.id}/${fmt}: ${e.message}`);
    }
  }
}

function buildSection(r, number, plan, usedInTest, withDI, diKind) {
  const areaCount = {};
  let figs = 0;
  const take = (fmt, slot) => {
    const t = pickTemplate(r, fmt, usedInTest, areaCount, figs < 2 && (slot === 1 || slot >= 5));
    if (t.fig) figs++;
    usedInTest.add(t.id); usage[t.id]++; areaCount[t.area] = (areaCount[t.area] || 0) + 1;
    return genItem(t, fmt, r);
  };
  let slot = 0;
  const qcs = []; for (let i = 0; i < plan.QC; i++) qcs.push(take('QC', slot++));
  const others = [];
  for (const fmt of ['MC', 'MA', 'NE']) for (let i = 0; i < plan[fmt]; i++) others.push(take(fmt, slot++));
  const shuffled = r.shuffle(others);
  let seq = [...qcs];
  if (withDI) {
    const di = (diKind === 'growth' ? diGrowth : diBudget)(r);
    const fmts = ['MC', 'NE', 'MA'];
    const diItems = di.items.map((core, i) => {
      const t = { id: 'di_' + diKind, area: 'Data Analysis', topic: di.topic };
      const fmt = core.kind === 'ma' ? 'MA' : (i === 1 || i === 0 && diKind === 'budget' ? 'NE' : 'MC');
      const it = finalize(t, core, fmt, r);
      it.q.diGroup = `S${number}-DI`;
      return it;
    });
    seq = [...seq, ...shuffled.slice(0, 4), ...diItems, ...shuffled.slice(4)];
  } else seq = [...seq, ...shuffled];
  return seq;
}

function buildTest(n) {
  const r = new Rng(SEED + n * 7919);
  const used = new Set();
  const s1 = buildSection(r, 1, { QC: 4, MC: 4, MA: 1, NE: 3 }, used, false);
  const s2 = buildSection(r, 2, { QC: 4, MC: 4, MA: 1, NE: 3 }, used, true, n % 2 ? 'growth' : 'budget');
  const exp = {};
  const sections = [s1, s2].map((items, si) => ({
    number: si + 1, timeLimit: si === 0 ? 21 : 26,
    questions: items.map((it, qi) => {
      const id = `S${si + 1}-Q${qi + 1}`;
      exp[id] = it.exp;
      return { id, ...it.q };
    }),
  }));
  return { examData: { title: 'GRE Quantitative Reasoning Mock Practice Test', round: `${n}회`, number: n, sections }, exp };
}

function pad(n) { return String(n).padStart(2, '0'); }

function pageHtml(n, examData) {
  return `<!DOCTYPE html>
<html lang="ko">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>GRE Quant Mock Test ${n}회</title>
<link rel="stylesheet" href="css/explanation.css">
<link rel="stylesheet" href="css/ets_gre_exam.css">
<link rel="stylesheet" href="css/quant.css">
<script src="js/quant_explanations_${pad(n)}.js"></script>
<script src="js/quant_history_manager.js"></script>
<script src="js/quant_exam.js"></script>
</head>
<body>
<div id="app"></div>
<div id="modal-root"></div>
<script>
// ============================================================
// EXAM DATA (generated by gen/build.js — do not edit by hand)
// ============================================================
const examData = ${JSON.stringify(examData, null, 2)};
QuantExam.boot(examData, window.QEXPLANATIONS_${pad(n)});
</script>
</body>
</html>
`;
}

function main() {
  fs.mkdirSync(path.join(ROOT, 'js'), { recursive: true });
  const summary = [];
  for (let n = 1; n <= NUM_TESTS; n++) {
    const { examData, exp } = buildTest(n);
    fs.writeFileSync(path.join(ROOT, `Quant_Mock_${pad(n)}.html`), pageHtml(n, examData));
    fs.writeFileSync(path.join(ROOT, 'js', `quant_explanations_${pad(n)}.js`), `window.QEXPLANATIONS_${pad(n)} = ${JSON.stringify(exp, null, 2)};\n`);
    const types = {}; examData.sections.forEach(s => s.questions.forEach(q => { types[q.type] = (types[q.type] || 0) + 1; }));
    summary.push({ n, types });
  }
  fs.writeFileSync(path.join(ROOT, 'js', 'quant_tests_index.js'), `window.QUANT_TESTS = ${JSON.stringify(summary.map(s => ({ n: s.n, file: `Quant_Mock_${pad(s.n)}.html`, types: s.types })))};\n`);
  console.log('templates:', TEMPLATES.length);
  console.log('usage:', Object.entries(usage).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}:${v}`).join(' '));
  console.log('built', NUM_TESTS, 'tests');
}

if (require.main === module) main();
module.exports = { TEMPLATES, buildTest };
